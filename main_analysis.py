import pandas as pd

df = pd.read_excel("Sample data.xlsx")

df.shape

df.head()

df.tail()

df.columns

df.describe()

df.info()

df.columns = df.columns.str.strip()
finance_cols = ['Units Sold', 'Gross Sales', 'Discounts', 'Sales', 'COGS', 'Profit']
for col in finance_cols:
  df[col] = pd.to_numeric(df[col], errors = "coerce")

df.drop('Discount Band', axis=1, inplace=True)

df.groupby("Segment").agg(Total_Units_Sold = ("Units Sold", "sum"),
                          Gross_Sales = ("Gross Sales", "sum"),
                          Total_Discounts=('Discounts', 'sum'),
                          Net_Sales=('Sales', 'sum'),
                          Total_COGS=('COGS', 'sum'),
                          Net_Profit=('Profit', 'sum')).reset_index()